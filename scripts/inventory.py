#!/usr/bin/env python3
"""Generate ENos physical-file counts and hashes, with an explicit inventory scope."""
from __future__ import annotations
import argparse
from collections import Counter
import hashlib
import json
from pathlib import Path
import re
import subprocess

ROOT=Path(__file__).resolve().parents[1]
SKIP={'.git','.venv','venv','node_modules','__pycache__','.pytest_cache','.mypy_cache','.ruff_cache','htmlcov','build','dist'}

def selected_files(root):
    # A source archive has no .git; apply the same documented cache exclusions.
    if (root/'.git').is_dir():
        run=subprocess.run(['git','ls-files','--cached','--others','--exclude-standard','-z'],cwd=root,capture_output=True,check=True)
        files=[root/Path(p.decode()) for p in run.stdout.split(b'\0') if p]
    else:files=[p for p in root.rglob('*') if p.is_file()]
    return sorted({p for p in files if p.is_file() and not any(x in SKIP or x.endswith('.egg-info') for x in p.relative_to(root).parts) and p.suffix not in {'.pyc','.pyo'}},key=lambda p:p.relative_to(root).as_posix())

def main():
    ap=argparse.ArgumentParser(description=__doc__);ap.add_argument('--root',type=Path,default=ROOT);ap.add_argument('--output',type=Path);ap.add_argument('--update-readme',action='store_true');args=ap.parse_args()
    root=args.root.resolve();out=(args.output or root/'REPOSITORY_INVENTORY.json').resolve()
    if not out.exists():out.write_text('{}\n')
    files=selected_files(root);ext=Counter(p.suffix.lower() or '<none>' for p in files)
    bank=[p for p in files if p.suffix in {'.yaml','.yml'} and 'formative' in p.parts and 'quiz' in p.stem.lower()]
    png=[p for p in files if p.suffix=='.png' and p.parent==root/'00_SUPPLEMENTARY/diagrams_png']
    counts={'files':len(files),'markdown':ext['.md'],'html':ext['.html'],'python':ext['.py'],'bash':ext['.sh'],'png':ext['.png'],'lecture_png':len(png),'svg':ext['.svg'],'yaml_all':ext['.yaml']+ext['.yml'],'formative_quiz_files':len(bank),'plantuml':ext['.puml']}
    table='| File category | Count |\n| --- | ---: |\n'+''.join(f'| {label} | {counts[key]} |\n' for key,label in [('files','Selected physical repository files'),('markdown','Markdown'),('html','HTML files, including exports and vendored support pages'),('python','Python source files, including tests'),('bash','Shell files'),('lecture_png','Generated lecture PNG diagrams'),('svg','SVG files'),('yaml_all','All YAML files'),('formative_quiz_files','Formative YAML quiz files'),('plantuml','PlantUML files, including shared style')])+'\nGenerated by `scripts/inventory.py`; [file hashes and scope](REPOSITORY_INVENTORY.json).'
    if args.update_readme:
        p=root/'README.md';s=p.read_text();s,n=re.subn(r'<!-- inventory:start -->.*?<!-- inventory:end -->','<!-- inventory:start -->\n'+table+'\n<!-- inventory:end -->',s,flags=re.S)
        if n!=1:raise ValueError('Expected one README inventory marker pair')
        p.write_text(s)
    rows=[]
    for p in files:
        rows.append({'path':p.relative_to(root).as_posix(),'size':None if p.resolve()==out else p.stat().st_size,'sha256':None if p.resolve()==out else hashlib.sha256(p.read_bytes()).hexdigest()})
    report={'baseline':'d8fdd0507fe26e6bc1438a692da14afc2112464c','version':'6.0.0','scope':'Tracked plus untracked non-ignored files when .git is present; otherwise archive physical files. Generated caches/build environments are excluded. The inventory includes itself in counts but omits its own hash/size to avoid self-reference. Counts do not establish coverage or execution.','counts':counts,'extensions':dict(sorted(ext.items())),'quiz_paths':[str(p.relative_to(root)) for p in bank],'files':rows}
    out.write_text(json.dumps(report,ensure_ascii=False,indent=2)+'\n');print(json.dumps(counts,sort_keys=True))

if __name__=='__main__':main()
