#!/usr/bin/env python3
"""Verify pinned assets offline, or explicitly restore their exact package bytes.

--restore downloads only tarballs already frozen in the committed manifests.
This command never updates package versions or executes npm lifecycle scripts.
"""
from __future__ import annotations
import argparse
import base64
import hashlib
import io
import json
import os
from pathlib import Path
import re
import tarfile
import tempfile
from urllib.parse import urlsplit
from urllib.request import urlopen

ROOT = Path(__file__).resolve().parents[2]
VENDOR = ROOT / 'assets/vendor'


def digest(data):
    return hashlib.sha256(data).hexdigest()


def destination(relative):
    path = (ROOT / relative).resolve()
    if not path.is_relative_to(VENDOR) or path == VENDOR:
        raise ValueError(f'Asset path outside vendor directory: {relative}')
    return path


def font_css(packages, read):
    chunks = []
    for package in packages:
        name = package['npm_name'].split('/')[-1]
        prefix = f"assets/vendor/fontsource/{name}/{package['version']}/"
        available = {entry['package_path'] for entry in package['files']}
        for filename in package['css_order']:
            if filename not in available:
                raise ValueError('Font CSS order references a missing package file')
            css = read(prefix + filename).decode('utf-8')
            css = re.sub(r'url\(([\"\']?)(?:\./)?(files/[^\)\"\']+)([\"\']?)\)',
                         lambda m: 'url('+m[1]+f"fontsource/{name}/{package['version']}/"+m[2]+m[3]+')', css)
            chunks.append(css)
    return ('/* ENos local font aggregation. Original package CSS and licence files are retained. */\n'+'\n'.join(chunks)).encode('utf-8')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--restore', action='store_true', help='Explicitly download and restore the exact manifest versions')
    args = parser.parse_args()
    try:
        general = json.loads((VENDOR/'MANIFEST.json').read_text())
        fonts = json.loads((VENDOR/'FONTS_MANIFEST.json').read_text())
        packages = general['packages'] + fonts['packages']
        payloads = {}
        for package in packages:
            if args.restore:
                url = package['tarball']
                parts = urlsplit(url)
                if parts.scheme != 'https' or parts.netloc != 'registry.npmjs.org':
                    raise ValueError('Tarballs must use the pinned HTTPS npm registry URL')
                with urlopen(url, timeout=45) as response:
                    raw = response.read()
                algorithm, expected = package['npm_integrity'].split('-', 1)
                if base64.b64encode(hashlib.new(algorithm, raw).digest()).decode() != expected or digest(raw) != package['tarball_sha256']:
                    raise ValueError(f"Tarball integrity mismatch: {package['npm_name']}")
                with tarfile.open(fileobj=io.BytesIO(raw), mode='r:gz') as archive:
                    for entry in package['files']:
                        member = archive.getmember('package/'+entry['package_path'])
                        if not member.isfile():
                            raise ValueError('Only regular package files may be restored')
                        payloads[entry['path']] = archive.extractfile(member).read()
            for entry in package['files']:
                path = destination(entry['path'])
                data = payloads[entry['path']] if args.restore else path.read_bytes()
                if digest(data) != entry['sha256'] or len(data) != entry['bytes']:
                    raise ValueError(f"Asset integrity mismatch: {entry['path']}")
        read = (lambda p: payloads[p]) if args.restore else (lambda p: destination(p).read_bytes())
        generated = font_css(fonts['packages'], read)
        font_record = fonts['generated_css']
        if digest(generated) != font_record['sha256']:
            raise ValueError('Reconstructed font CSS does not match the committed manifest')
        if args.restore:
            payloads[font_record['path']] = generated
            # All package and generated bytes have passed before publication.
            for relative, data in payloads.items():
                path = destination(relative)
                path.parent.mkdir(parents=True, exist_ok=True)
                with tempfile.NamedTemporaryFile(dir=path.parent, delete=False) as handle:
                    handle.write(data)
                    pending = Path(handle.name)
                try:
                    os.chmod(pending, 0o644)
                    os.replace(pending, path)
                finally:
                    pending.unlink(missing_ok=True)
        elif destination(font_record['path']).read_bytes() != generated:
            raise ValueError('Committed combined font CSS differs from its package sources')
        count = sum(len(package['files']) for package in packages)
        print(f'PASS: {len(packages)} pinned package versions, {count} package files and reproducible font CSS')
        return 0
    except (OSError, ValueError, KeyError, tarfile.TarError) as exc:
        print(f'FAIL: {exc}')
        return 1


if __name__ == '__main__':
    raise SystemExit(main())
